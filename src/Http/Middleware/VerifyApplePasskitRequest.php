<?php

namespace Spatie\LaravelMobilePass\Http\Middleware;

use Closure;
use Illuminate\Http\Request;
use Spatie\LaravelMobilePass\Support\Apple\AuthenticationToken;
use Spatie\LaravelMobilePass\Support\Config;

class VerifyApplePasskitRequest
{
    public function handle(Request $request, Closure $next): mixed
    {
        $providedAuthorization = (string) $request->header('Authorization');
        $passSerial = (string) $request->route('passSerial');
        $secret = config('mobile-pass.apple.webservice.secret');

        if (! is_string($secret) || $secret === '') {
            abort(401);
        }

        if (hash_equals('ApplePass '.AuthenticationToken::forSerial($passSerial), $providedAuthorization)) {
            return $next($request);
        }

        if (hash_equals("ApplePass {$secret}", $providedAuthorization)) {
            if ($this->passCarriesSharedSecret($passSerial, $secret)) {
                return $next($request);
            }
        }

        abort(401);
    }

    /**
     * Passes generated by older versions of this package carry the secret
     * itself as their token, and Apple doesn't let an update change it.
     */
    protected function passCarriesSharedSecret(string $passSerial, string $secret): bool
    {
        if (! config('mobile-pass.apple.webservice.accept_shared_secret', true)) {
            return false;
        }

        $pass = Config::mobilePassModel()::query()
            ->where('pass_serial', $passSerial)
            ->first();

        return ($pass?->content['authenticationToken'] ?? null) === $secret;
    }
}
